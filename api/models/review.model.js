import mongoose from "mongoose";

const ReviewSchemaModel = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    productId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Product",
      required: true,
    },
    commentReview: {
      type: String,
      required: true,
    },
    rating: {
      type: Number,
      required: true,
      min: 1,
      max: 5,
    },
  },

  {
    timestamps: true,
  }
);

const Review = mongoose.model("Review", ReviewSchemaModel);

export default Review;
