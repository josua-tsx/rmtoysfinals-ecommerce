import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

const COLORS = {
  primary: "#1a1a1a",
  secondary: "#666666",
  accent: "#22c55e",
  border: "#000000",
  lightBg: "#f9fafb",
};

/**
 * Common header for all reports
 */
const addHeader = (doc, data, title) => {
  const pageWidth = doc.internal.pageSize.width;

  // Store Name
  doc.setFontSize(22);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(COLORS.primary);
  doc.text(data.storeName || "RM TOYS", 20, 20);

  // Address & Contacts
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(COLORS.secondary);
  doc.text(data.storeAddress || "", 20, 26);
  doc.text(`${data.storePhone} | ${data.storeEmail}`, 20, 31);

  // Report Title & Meta
  doc.setFontSize(16);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(COLORS.accent);
  doc.text(title, pageWidth - 20, 20, { align: "right" });

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(COLORS.secondary);
  doc.text(`Generated: ${data.generatedAt}`, pageWidth - 20, 26, {
    align: "right",
  });
  if (data.dateRange) {
    doc.setFillColor(243, 244, 246);
    doc.rect(pageWidth - 70, 30, 50, 6, "F");
    doc.setFont("courier", "normal");
    doc.setFontSize(9);
    doc.text(data.dateRange, pageWidth - 45, 34, { align: "center" });
  }

  // Divider Line
  doc.setDrawColor(0);
  doc.setLineWidth(1);
  doc.line(20, 40, pageWidth - 20, 40);
};

/**
 * Add summary cards
 */
const addSummaryCards = (doc, cards, startY) => {
  const pageWidth = doc.internal.pageSize.width;
  const margin = 20;
  const gap = 10;
  const totalGaps = (cards.length - 1) * gap;
  const availableWidth = pageWidth - (margin * 2) - totalGaps;
  const cardWidth = availableWidth / cards.length;
  const cardHeight = 25;
  let currentX = margin;

  cards.forEach((card) => {
    // Card Box
    doc.setDrawColor(COLORS.border);
    doc.setFillColor(249, 250, 251);
    doc.rect(currentX, startY, cardWidth, cardHeight, "FD");

    // Title
    doc.setFontSize(8);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(COLORS.secondary);
    doc.text(card.title.toUpperCase(), currentX + cardWidth / 2, startY + 8, {
      align: "center",
    });

    // Value
    doc.setFontSize(14);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(
      card.highlight ? COLORS.accent : COLORS.primary
    );
    doc.text(card.value.toString(), currentX + cardWidth / 2, startY + 18, {
      align: "center",
    });

    currentX += cardWidth + gap;
  });
};

/**
 * Add footer
 */
const addFooter = (doc, data) => {
  const pageHeight = doc.internal.pageSize.height;
  doc.setDrawColor(200);
  doc.setLineWidth(0.5);
  doc.setLineDash([2, 2], 0);
  doc.line(20, pageHeight - 20, doc.internal.pageSize.width - 20, pageHeight - 20);

  doc.setFontSize(8);
  doc.setTextColor(156, 163, 175);
  doc.text(
    "This is a computer-generated report. No signature required.",
    doc.internal.pageSize.width / 2,
    pageHeight - 15,
    { align: "center" }
  );
  doc.text(
    `Generated by ${data.storeName} Admin Dashboard`,
    doc.internal.pageSize.width / 2,
    pageHeight - 10,
    { align: "center" }
  );
};

