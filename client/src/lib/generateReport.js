export const generateInventoryPDF = (data) => {
  const doc = new jsPDF();

  addHeader(doc, data, "INVENTORY REPORT");

  // Summary Cards
  const cards = [
    { title: "Total Products", value: data.totalProducts },
    { title: "Low Stock", value: data.lowStockCount, highlight: true },
    { title: "Out of Stock", value: data.outOfStockCount },
  ];
  addSummaryCards(doc, cards, 50);

  // Table
  autoTable(doc, {
    startY: 85,
    head: [["Product", "Category", "Price", "Stock", "Status"]],
    body: data.products.map((p) => [
      p.productName,
      p.category,
      `P${p.price.toLocaleString()}`,
      p.stock,
      p.stockStatus,
    ]),
    theme: "grid",
    headStyles: { fillColor: COLORS.primary, textColor: 255 },
    styles: { fontSize: 8 },
    columnStyles: {
      2: { halign: "right" },
      3: { halign: "center" },
    },
    didParseCell: function (data) {
      if (data.section === "body" && data.column.index === 4) {
        if (data.cell.raw === "Out of Stock") {
            data.cell.styles.textColor = [220, 38, 38]; // Red
        } else if (data.cell.raw === "Low Stock") {
            data.cell.styles.textColor = [217, 119, 6]; // Orange/Amber
        } else {
            data.cell.styles.textColor = [22, 163, 74]; // Green
        }
      }
    },
  });

  addFooter(doc, data);
  doc.save(`Inventory-Report-${new Date().toISOString().split("T")[0]}.pdf`);
};

export const generateInvoicePDF = (data) => {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.width;

  // --- HEADER: STORE INFO ---
  doc.setFontSize(24);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(COLORS.primary);
  doc.text(data.storeName, 20, 20);

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(COLORS.secondary);
  doc.text(data.storeAddress, 20, 26);
  doc.text(`${data.storePhone} | ${data.storeEmail}`, 20, 31);

  // --- INVOICE TITLE & META ---
  doc.setFontSize(26);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(COLORS.accent); // Brand color for INVOICE
  doc.text("INVOICE", pageWidth - 20, 25, { align: "right" });

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(COLORS.secondary);
  doc.text(`Order ID: ${data.orderId}`, pageWidth - 20, 32, { align: "right" });
  doc.text(`Date: ${data.orderDate}`, pageWidth - 20, 37, { align: "right" });

  // Divider
  doc.setDrawColor(200);
  doc.line(20, 45, pageWidth - 20, 45);

  // --- CUSTOMER & SHIPPING INFO ---
  const leftColX = 20;
  const rightColX = pageWidth / 2 + 10;
  const sectionY = 55;

  // Bill To
  doc.setFontSize(10);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(COLORS.primary);
  doc.text("BILL TO:", leftColX, sectionY);
  
  doc.setFont("helvetica", "normal");
  doc.setTextColor(COLORS.secondary);
  doc.text(data.customerName, leftColX, sectionY + 6);
  doc.text(data.customerEmail, leftColX, sectionY + 11);
  doc.text(data.customerPhone, leftColX, sectionY + 16);

  // Ship To (Address)
  doc.setFont("helvetica", "bold");
  doc.setTextColor(COLORS.primary);
  doc.text("SHIP TO:", rightColX, sectionY);

  doc.setFont("helvetica", "normal");
  doc.setTextColor(COLORS.secondary);
  // Split long addresses
  const addressLines = doc.splitTextToSize(data.shippingAddress, pageWidth / 2 - 30);
  doc.text(addressLines, rightColX, sectionY + 6);

  // --- PAYMENT STATUS BADGE ---
  const badgeY = sectionY + 30;
  
  doc.setFontSize(10);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(COLORS.primary);
  doc.text("PAYMENT METHOD:", leftColX, badgeY);
  doc.setFont("helvetica", "normal");
  doc.text(data.paymentMethod, leftColX, badgeY + 6);

  // Status Box
  const statusColor = data.paymentStatus === "Paid" ? [34, 197, 94] : [239, 68, 68]; // Green or Red
  doc.setFillColor(...statusColor);
  doc.roundedRect(rightColX, badgeY - 2, 40, 10, 2, 2, "F");
  
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.text(data.paymentStatus.toUpperCase(), rightColX + 20, badgeY + 4, { align: "center" });

  // --- ORDER ITEMS TABLE ---
  autoTable(doc, {
    startY: badgeY + 20,
    head: [["Item Description", "Category", "Qty", "Unit Price", "Total"]],
    body: data.orderItems.map((item) => [
      item.productName,
      item.category,
      item.quantity,
      `P${item.unitPrice.toLocaleString('en-US', {minimumFractionDigits: 2})}`,
      `P${item.totalPrice.toLocaleString('en-US', {minimumFractionDigits: 2})}`,
    ]),
    theme: "striped",
    headStyles: { 
      fillColor: COLORS.primary, 
      textColor: 255,
      fontStyle: "bold" 
    },
    columnStyles: {
      0: { cellWidth: 70 }, // Description
      2: { halign: "center" }, // Qty
      3: { halign: "right" }, // Price
      4: { halign: "right", fontStyle: "bold" }, // Total
    },
  });

  // --- TOTALS SECTION ---
  let finalY = doc.lastAutoTable.finalY + 10;
  const totalsX = pageWidth - 70;
  const valueX = pageWidth - 20;
  const step = 7;

  // Helper for totals row
  const addTotalRow = (label, value, isBold = false) => {
    doc.setFont("helvetica", isBold ? "bold" : "normal");
    doc.setTextColor(COLORS.primary);
    doc.setFontSize(10);
    doc.text(label, totalsX, finalY);
    doc.text(value, valueX, finalY, { align: "right" });
    finalY += step;
  };

  addTotalRow("Subtotal:", `P${data.subtotal.toLocaleString('en-US', {minimumFractionDigits: 2})}`);
  addTotalRow("Shipping:", `P${data.shippingPrice.toLocaleString('en-US', {minimumFractionDigits: 2})}`);
  
  if (data.vatAmount > 0) {
    addTotalRow("VAT (12%):", `P${data.vatAmount.toLocaleString('en-US', {minimumFractionDigits: 2})}`);
  }
  
  if (data.usedCredits > 0) {
    doc.setTextColor(239, 68, 68); // Red for discount
    addTotalRow("Credits Used:", `-P${data.usedCredits.toLocaleString('en-US', {minimumFractionDigits: 2})}`);
    doc.setTextColor(COLORS.primary); // Reset
  }

  // Grand Total Line
  doc.setDrawColor(200);
  doc.line(totalsX - 10, finalY - 4, pageWidth - 20, finalY - 4);
  finalY += 2;

  // Grand Total
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.setTextColor(COLORS.accent);
  doc.text("TOTAL:", totalsX, finalY + 2);
  doc.text(`P${data.totalPrice.toLocaleString('en-US', {minimumFractionDigits: 2})}`, valueX, finalY + 2, { align: "right" });

  // --- FOOTER ---
  const pageHeight = doc.internal.pageSize.height;
  doc.setDrawColor(200);
  doc.setLineWidth(0.5);
  doc.setLineDash([2, 2], 0);
  doc.line(20, pageHeight - 20, pageWidth - 20, pageHeight - 20);

  doc.setFontSize(8);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(156, 163, 175);
  doc.text(
    "Thank you for your business!",
    pageWidth / 2,
    pageHeight - 15,
    { align: "center" }
  );
  doc.text(
    `Order ID: ${data.orderId} | Generated by ${data.storeName}`,
    pageWidth / 2,
    pageHeight - 10,
    { align: "center" }
  );

  doc.save(`Invoice-${data.orderId.slice(-8)}.pdf`);
};
